#!/usr/bin/env python3
"""Build the C library for the smir64 target from the pinned LLVM libc.

    python3 -B build_libc.py [--llvm DIR] [--output DIR] [--jobs N] [--force]

The result is a sysroot: `include/`, the library's public headers, and
`lib/libc.bc`, the library as LLVM bitcode for `smir-clang --library`. The
LLVM checkout is read, never modified. Prints the sysroot's path.

--llvm defaults as in ../build.py. --output defaults to
crates/smir-portable/target/smir-sysroot, which git ignores. The build is
skipped when a sysroot built from the same inputs is already there.

What is built is LLVM libc's freestanding ("baremetal") configuration: every
entry point its list for 32-bit Arm names outside a conditional block, except
those in EXCLUDED. The library is compiled as LLVM's build would compile it,
with these differences, all on the command line or in files here:

- The embedder's side (the standard streams, the end of the program, the
  error number) is `platform.c`, over the runtime services.
- The heap is one zero-filled object of HEAP_BYTES bytes, which `malloc`
  carves up.
- `overlay/` supplies the one header that names no layout for an unknown
  architecture, `fenv_t`.
- `printf` converts floating point, which the baremetal configuration turns
  off to save space.

The public headers are generated by LLVM libc's own generator, which needs
Python with PyYAML. This script looks for one and says so if there is none.
"""
import argparse
from concurrent.futures import ThreadPoolExecutor
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
sys.path.insert(0, str(HERE.parent))

import build as driver  # noqa: E402

HEAP_BYTES = 1 << 20
NAMESPACE = '__llvm_libc_smir'
SERVICES = ROOT / 'docs/specifications/smir/portable/schema/runtime/services-v1.json'

# Entry points of the baremetal list that are not built, and why.
EXCLUDED = {
    'libc.src.setjmp.setjmp': 'written in assembly for each architecture',
    'libc.src.setjmp.longjmp': 'written in assembly for each architecture',
    'libc.src.string.memset_explicit': 'uses inline assembly to keep the store',
    'libc.src.stdlib._Exit': 'platform.c defines it, to end the program without finalizers',
    'libc.src.time.localtime': 'its baremetal source does not compile at the pinned revision',
    'libc.src.time.localtime_r': 'its baremetal source does not compile at the pinned revision',
    'libc.startup.baremetal.init': 'the engine runs initializers',
    'libc.startup.baremetal.fini': 'the engine runs finalizers',
}

# Sources that are not entry points but that entry points call.
SUPPORT = [
    'src/__support/CPP/new.cpp',
    'src/__support/OSUtil/baremetal/exit.cpp',
    'src/__support/OSUtil/baremetal/io.cpp',
    'src/__support/StringUtil/error_to_string.cpp',
    'src/__support/freelist.cpp',
    'src/__support/freelist_heap.cpp',
    'src/__support/freetrie.cpp',
    'src/locale/locale.cpp',
    'src/stdio/baremetal/file_internal.cpp',
    'src/stdlib/rand_util.cpp',
    'src/time/time_utils.cpp',
]

# Public headers generated from LLVM libc's descriptions.
HEADERS = ['assert', 'ctype', 'errno', 'fenv', 'float', 'inttypes', 'limits', 'locale', 'math', 'stdbit',
           'stdint', 'stdio', 'stdlib', 'string', 'strings', 'time', 'wchar', 'wctype']

# How LLVM's build compiles the library for a freestanding target.
FLAGS = [
    '-O2', '-std=c++17', '-fno-builtin', '-DNDEBUG',
    f'-DLIBC_NAMESPACE={NAMESPACE}', '-DLIBC_FULL_BUILD', '-DLIBC_COPT_PUBLIC_PACKAGING',
    '-DLIBC_THREAD_MODE=LIBC_THREAD_MODE_SINGLE', '-DLIBC_ERRNO_MODE=LIBC_ERRNO_MODE_EXTERNAL',
    '-DLIBC_QSORT_IMPL=LIBC_QSORT_HEAP_SORT',
    '-DLIBC_COPT_PRINTF_DISABLE_INDEX_MODE', '-DLIBC_COPT_PRINTF_DISABLE_WRITE_INT',
    '-DLIBC_COPT_PRINTF_DISABLE_FIXED_POINT', '-DLIBC_COPT_PRINTF_DISABLE_STRERROR',
    '-DLIBC_COPT_PRINTF_DISABLE_WIDE', '-DLIBC_COPT_PRINTF_DISABLE_BITINT',
    '-DLIBC_COPT_SCANF_DISABLE_INDEX_MODE',
]


class BuildError(Exception):
    pass


def default_output():
    return ROOT / 'crates/smir-portable/target/smir-sysroot'


def entry_points(libc):
    """The entry points the baremetal list names outside any conditional block, in order."""
    names, depth = [], 0
    for line in (libc / 'config/baremetal/arm/entrypoints.txt').read_text().splitlines():
        line = line.split('#')[0].strip()
        if re.match(r'if\s*\(', line):
            depth += 1
        elif line.startswith('endif'):
            depth -= 1
        elif depth == 0 and line.startswith('libc.') and line not in names:
            names.append(line)
    return names


def source_of(libc, entry):
    """The file that defines an entry point: its freestanding variant if there is one."""
    parts = entry.split('.')
    if entry == 'libc.src.errno.errno':
        return libc / 'src/errno/libc_errno.cpp'
    directory, name = libc.joinpath(*parts[1:-1]), parts[-1] + '.cpp'
    for variant in ('baremetal', 'generic', ''):
        candidate = directory / variant / name
        if candidate.exists():
            return candidate
    return None


def generator():
    """A Python that can run LLVM libc's header generator, which needs PyYAML."""
    candidates = [sys.executable] + [shutil.which(f'python3.{minor}') for minor in range(20, 8, -1)]
    for candidate in filter(None, candidates):
        probe = subprocess.run([candidate, '-B', '-c', 'import yaml'], capture_output=True)
        if probe.returncode == 0:
            return candidate
    raise BuildError('no Python with PyYAML found; the libc header generator needs one '
                     '(python3 -m pip install pyyaml)')


def install_headers(libc, include, entries):
    """Generate the public headers and copy the ones LLVM libc ships as they are.

    A header declares the functions among `entries` only, as in LLVM's own
    build: what is declared is what the library has.
    """
    python = generator()
    include.mkdir(parents=True)
    # The generator is run from the checkout without leaving bytecode in it.
    environment = dict(os.environ, PYTHONDONTWRITEBYTECODE='1')
    declared = [f'--entry-point={entry.split(".")[-1]}' for entry in entries] + ['--entry-point=_Exit']
    for name in HEADERS:
        run = subprocess.run([python, '-B', str(libc / 'utils/hdrgen/main.py'), '--output',
                              str(include / f'{name}.h'), str(libc / f'include/{name}.yaml'), *declared],
                             capture_output=True, text=True, env=environment)
        if run.returncode != 0:
            raise BuildError(f'cannot generate {name}.h:\n{run.stderr[-2000:]}')
    shutil.copy(libc / 'include/__llvm-libc-common.h', include)
    for directory in ('llvm-libc-macros', 'llvm-libc-types'):
        shutil.copytree(libc / 'include' / directory, include / directory)
    # A printf that the optimizer may split into parts needs linker support
    # this target does not have; LLVM's build installs this variant as well.
    macros = include / 'llvm-libc-macros'
    shutil.copy(macros / '_LIBC_MODULAR_FORMAT_PRINTF-disable.h', macros / '_LIBC_MODULAR_FORMAT_PRINTF.h')
    shutil.copytree(HERE / 'overlay/include', include, dirs_exist_ok=True)


def heap(datalayout):
    """The heap as LLVM IR: one object, and the two names the allocator knows its ends by."""
    return (f'{datalayout}\ntarget triple = "smir64-unknown-rax"\n'
            f'@__smir_heap = internal global [{HEAP_BYTES} x i8] zeroinitializer, align 16\n'
            '@_end = hidden alias i8, ptr @__smir_heap\n'
            f'@__llvm_libc_heap_limit = hidden alias i8, getelementptr (i8, ptr @__smir_heap, i64 {HEAP_BYTES})\n')


def build(llvm=None, output=None, jobs=None, force=False):
    llvm = Path(llvm or driver.default_llvm()).resolve()
    output = Path(output or default_output()).resolve()
    libc = llvm / 'libc'
    binary = driver.build(llvm)
    resource = sorted((llvm / 'build/lib/clang').iterdir())[-1]
    entries = [entry for entry in entry_points(libc) if entry not in EXCLUDED]
    sources = {}
    missing = []
    for entry in entries:
        source = source_of(libc, entry)
        if source is None:
            missing.append(entry)
        else:
            sources[source] = entry
    for relative in SUPPORT:
        sources[libc / relative] = relative
    if missing:
        raise BuildError('no source found for: ' + ', '.join(missing))

    # The sysroot is current if it was built by this script from the same
    # driver, the same library sources and the same files here.
    digest = hashlib.sha256()
    for item in [Path(__file__), HERE / 'platform.c', *sorted((HERE / 'overlay').rglob('*.h')), binary, *sources]:
        digest.update(str(item).encode() + b'\0' + str(item.stat().st_mtime_ns).encode() + b'\0')
    digest.update(driver.PIN.encode() + json.dumps(FLAGS).encode())
    stamp = output / 'stamp'
    if not force and stamp.exists() and stamp.read_text() == digest.hexdigest():
        return output

    if output.exists():
        shutil.rmtree(output)
    include, objects = output / 'include', output / 'obj'
    install_headers(libc, include, entries)
    objects.mkdir()
    common = [str(binary), '--resource-dir', str(resource), '--services', str(SERVICES),
              '-I', str(HERE.parent / 'include')]
    flags = [*FLAGS, '-I', str(HERE / 'overlay'), '-I', str(libc), '-isystem', str(include)]

    def compile_one(item):
        position, source = item
        target = objects / f'{position:04d}-{source.stem}.bc'
        run = subprocess.run([*common, *flags, '-c', '-o', str(target), str(source)], capture_output=True, text=True)
        return (source, None) if run.returncode == 0 else (source, run.stderr[-1500:])

    with ThreadPoolExecutor(max_workers=jobs or os.cpu_count() or 4) as pool:
        failures = [(source, error) for source, error in pool.map(compile_one, enumerate(sources)) if error]
    if failures:
        report = '\n'.join(f'{sources[source]} ({source.relative_to(libc)}):\n{error}' for source, error in failures[:8])
        raise BuildError(f'{len(failures)} of {len(sources)} library sources do not compile:\n{report}')

    # The platform file fixes the data layout the heap's IR must name.
    platform = objects / 'platform.ll'
    run = subprocess.run([*common, '-O2', '-isystem', str(include), '-c', '-o', str(objects / 'platform.bc'),
                          '--emit-llvm', str(platform), str(HERE / 'platform.c')], capture_output=True, text=True)
    if run.returncode != 0:
        raise BuildError('cannot compile platform.c:\n' + run.stderr[-2000:])
    datalayout = next(line for line in platform.read_text().splitlines() if line.startswith('target datalayout'))
    (objects / 'heap.ll').write_text(heap(datalayout))

    library = output / 'lib/libc.bc'
    library.parent.mkdir()
    undefined = objects / 'undefined.txt'
    run = subprocess.run([*common, '-c', '--undefined', str(undefined), '-o', str(library),
                          *map(str, sorted(objects.glob('*.bc'))), str(objects / 'heap.ll')],
                         capture_output=True, text=True)
    if run.returncode != 0:
        raise BuildError('cannot link the library:\n' + run.stderr[-3000:])
    # Everything the library refers to must be in it, except the runtime
    # services, which the compiler binds.
    left = [name for name in undefined.read_text().split() if not name.startswith('smir.portable.v1:')]
    if left:
        raise BuildError(f'the library refers to {len(left)} names it does not define; add their sources to '
                         'SUPPORT or exclude the entry points that need them:\n' + '\n'.join(left[:40]))
    stamp.write_text(digest.hexdigest())
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--llvm', type=Path)
    parser.add_argument('--output', type=Path)
    parser.add_argument('--jobs', type=int)
    parser.add_argument('--force', action='store_true')
    arguments = parser.parse_args()
    try:
        print(build(arguments.llvm, arguments.output, arguments.jobs, arguments.force))
    except (BuildError, driver.BuildError) as error:
        sys.exit(f'build_libc.py: {error}')


if __name__ == '__main__':
    main()
