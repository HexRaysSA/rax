#!/usr/bin/env python3
"""Reproduce A64 FEAT_FP16 admission masks from the pinned Arm ASL source.

Only four explicit decode predicates are translated. Unknown predicates or
source revisions fail rather than silently broadening the admission table.
Legacy half-storage and precision-conversion encodings have no such predicate.
"""

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/architecture/arm/asl/arm_instrs.asl"
SOURCE_SHA256 = "3c91ece6d0509f7ce9e8b2d8fa623787d7c7acb4cb24040a75cec5aa2789e611"
TABLE = ROOT / "src/isa/arm/aarch64/cpu/fp_profile/fp16_encodings.rs"
CORPUS = ROOT / "docs/development/a64-half-admission/encodings.json"


def constrain(pattern, low, bits):
    result = list(pattern)
    for offset, bit in enumerate(reversed(bits)):
        if bit == "x":
            continue
        index = 31 - low - offset
        assert result[index] in ("x", bit), (pattern, low, bits)
        result[index] = bit
    return "".join(result)


def parse():
    raw = SOURCE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError("unqualified ASL revision")
    source = raw.decode()
    records = {}
    boundaries = list(re.finditer(r"(?m)^    __encoding (\S+)\n|^__instruction ", source))
    for index, match in enumerate(boundaries):
        if match.group(1) is None:
            continue
        end = boundaries[index + 1].start() if index + 1 < len(boundaries) else len(source)
        block = source[match.start():end]
        if "__instruction_set A64" not in block or "HaveFP16Ext()" not in block:
            continue
        decode = block.split("__decode", 1)[1].split("__execute", 1)[0]
        pattern = re.search(r"__opcode '([^']+)'", block).group(1).replace(" ", "")
        assert len(pattern) == 32 and set(pattern) <= set("01x")
        fields = {name: (int(low), int(width)) for name, low, width in
                  re.findall(r"__field (\S+) (\d+) \+: (\d+)", block)}
        if decode.strip().startswith("if !HaveFP16Ext() then UNDEFINED;"):
            predicate = "unconditional"
            required = pattern
        elif re.search(r"when '11'\s+if HaveFP16Ext\(\) then", decode):
            assert fields["type1"] == (22, 2) and "case type1 of" in decode
            predicate = "type=11"
            required = constrain(pattern, 22, "11")
        elif "if !HaveFP16Ext() && esize == 16 then UNDEFINED;" in decode:
            assert fields["size"] == (22, 2) and "integer esize = 8 << UInt(size);" in decode
            predicate = "size=01"
            required = constrain(pattern, 22, "01")
        elif "(immh == '001x' && !HaveFP16Ext())" in decode:
            assert fields["immh"] == (19, 4)
            predicate = "immh=001x"
            required = constrain(pattern, 19, "001x")
        else:
            raise AssertionError((match.group(1), "unknown FP16 predicate"))
        mask = int("".join("0" if bit == "x" else "1" for bit in required), 2)
        value = int(required.replace("x", "0"), 2)
        assert ((value >> 25) & 15) in (7, 15)
        record = dict(name=match.group(1), pattern=pattern, predicate=predicate,
                      required_pattern=required, mask=mask, value=value)
        records[(record["name"], pattern, predicate)] = record
    assert len(records) == 64, len(records)
    return sorted(records.values(), key=lambda record: record["name"])


def outputs():
    records = parse()
    groups = {}
    for record in records:
        groups.setdefault((record["mask"], record["value"]), []).append(record["name"])
    lines = ["// Generated by tools/execution/a64_fp16_admission.py; do not edit.",
             "// Source: docs/architecture/arm/asl/arm_instrs.asl",
             f"// SHA-256: {SOURCE_SHA256}",
             "const REQUIRES_FP16: &[(u32, u32)] = &["]
    for (mask, value), names in sorted(groups.items()):
        lines.append(f"    // {', '.join(sorted(names))}")
        lines.append(f"    (0x{mask >> 16:04x}_{mask & 65535:04x}, 0x{value >> 16:04x}_{value & 65535:04x}),")
    lines += ["];", ""]
    corpus = dict(source=str(SOURCE.relative_to(ROOT)), source_sha256=SOURCE_SHA256,
                  encoding_descriptions=len(records), distinct_masks=len(groups), records=records)
    return "\n".join(lines), json.dumps(corpus, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write the two owned generated outputs")
    args = parser.parse_args()
    table, corpus = outputs()
    for path, expected in ((TABLE, table), (CORPUS, corpus)):
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(expected)
        else:
            assert path.read_text() == expected, f"stale generated output: {path}"
    report = json.loads(corpus)
    print(json.dumps({key: report[key] for key in ("source_sha256", "encoding_descriptions", "distinct_masks")}))


if __name__ == "__main__":
    main()
