#!/usr/bin/env python3
"""Derive the represented non-SVE optional FP/SIMD instruction patterns.

The frozen opcodesDB index supplies bit diagrams, not an independent semantic
oracle. Arm primary feature/ID documents and the retained LLVM/QEMU runs qualify
these patterns. The historical index's upstream revision remains unknown.
"""

import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "docs/architecture/arm/opcodesDB/db/aarch64/fpsimd/encodings.pl"
TABLE = ROOT / "src/isa/arm/aarch64/cpu/fp_profile/optional_encodings.rs"
CORPUS = ROOT / "docs/development/a64-optional-fp-profile/encodings.json"
SOURCE_SHA256 = "ef2487bbb53af2681982b1a69e63524aa4147857385783dab1d9e91a975c438c"
PREFIXES = {
    "JSCVT": ("FJCVTZS_",),
    "FCMA": ("FCADD_", "FCMLA_"),
    "FRINTTS": ("FRINT32X_", "FRINT32Z_", "FRINT64X_", "FRINT64Z_"),
    "BF16": ("BFCVT_", "BFCVTN_", "BFDOT_", "BFMLAL_", "BFMMLA_"),
    "I8MM": ("SMMLA_", "UMMLA_", "USMMLA_", "USDOT_", "SUDOT_"),
    "DOTPROD": ("SDOT_", "UDOT_"),
}


def outputs():
    raw = SOURCE.read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    if digest != SOURCE_SHA256:
        raise ValueError("unqualified encoding-index revision")
    records = []
    for name, block in re.findall(r"ENCODING (\w+) => \{(.*?)\n\};", raw.decode(), re.S):
        feature = next((key for key, prefixes in PREFIXES.items()
                        if name.startswith(prefixes)), None)
        if feature is None:
            continue
        diagram = re.search(r"diagram\s+=> '([^']+)'", block).group(1)
        pattern = "".join(re.findall(r"=0b([01x]+)", diagram))
        if len(pattern) != 32:
            raise ValueError(f"unqualified diagram: {name}")
        mask = int("".join("0" if bit == "x" else "1" for bit in pattern), 2)
        value = int(pattern.replace("x", "0"), 2)
        records.append(dict(name=name, feature=feature, pattern=pattern, mask=mask, value=value))
    if len(records) != 34:
        raise ValueError(f"unexpected encoding count: {len(records)}")
    records.sort(key=lambda row: (row["feature"], row["name"]))
    lines = ["// Generated by tools/execution/a64_optional_fp_profile.py; do not edit.",
             "// Encoding index: docs/architecture/arm/opcodesDB/db/aarch64/fpsimd/encodings.pl",
             f"// SHA-256: {digest}",
             "const OPTIONAL_ENCODINGS: &[(u32, u32, ArmFeatures)] = &["]
    for row in records:
        mask, value = row["mask"], row["value"]
        lines.append(f"    // {row['name']}")
        lines.append(f"    (0x{mask >> 16:04x}_{mask & 65535:04x}, "
                     f"0x{value >> 16:04x}_{value & 65535:04x}, ArmFeatures::{row['feature']}),")
    lines += ["];", ""]
    corpus = dict(encoding_index=str(SOURCE.relative_to(ROOT)), encoding_index_sha256=digest,
                  upstream_revision="unknown", encoding_index_role="Secondary bit-diagram index; not a semantic oracle.",
                  primary_documents="docs/development/a64-optional-fp-profile/primary/provenance.json",
                  records=records)
    return "\n".join(lines), json.dumps(corpus, indent=2) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    table, corpus = outputs()
    for path, expected in ((TABLE, table), (CORPUS, corpus)):
        if args.write:
            path.write_text(expected)
        elif path.read_text() != expected:
            raise ValueError(f"stale generated output: {path}")
    print(json.dumps(dict(encodings=34, counts={key: sum(row["feature"] == key for row in
                         json.loads(corpus)["records"]) for key in PREFIXES})))


if __name__ == "__main__":
    main()
