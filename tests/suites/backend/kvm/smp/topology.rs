fn profile_cpuid(vm: &Vmm, id: u8, leaf: u32, index: u32) -> [u32; 4] {
    let row = QUERIES
        .iter()
        .position(|query| *query == (leaf, index))
        .unwrap();
    std::array::from_fn(|word| {
        vm.guest_mem()
            .memory()
            .read_obj(GuestAddress(
                0x250000 + u64::from(id) * 1024 + row as u64 * 16 + word as u64 * 4,
            ))
            .unwrap()
    })
}

fn run_profile(count: u8, name: &str, clock_only: bool) {
    if std::env::var(CHILD).as_deref() != Ok(name) {
        let output = Command::new(std::env::current_exe().unwrap())
            .args([
                "--ignored",
                "--exact",
                name,
                "--nocapture",
                "--test-threads=1",
            ])
            .env(CHILD, name)
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}\n{}\n{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        print!("{}", String::from_utf8_lossy(&output.stdout));
        return;
    }
    let path = std::env::temp_dir().join(format!("rax-kvm-profile-{}-{count}", std::process::id()));
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .unwrap();
    let kernel = Kernel(path);
    let mut image = vec![0; 0x200];
    image.extend_from_slice(PROFILE_BSP);
    assert!(image.len() <= 0x1200);
    image.resize(0x1200, 0);
    image.extend_from_slice(PROFILE_AP);
    image.resize(0x2200, 0);
    file.write_all(&image).unwrap();
    drop(file);
    let mut config = VmConfig::from_sources(
        CliConfig {
            arch: Some(ArchKind::X86_64),
            backend: Some(BackendKind::Kvm),
            vcpus: Some(count),
            kernel: Some(kernel.0.clone()),
            ..Default::default()
        },
        None,
    )
    .unwrap();
    config.memory = MemorySize(64 * 1024 * 1024);
    let mut vm = Vmm::new(config).unwrap();
    vm.guest_mem()
        .memory()
        .write_obj(u32::from(count), GuestAddress(0x210000))
        .unwrap();
    vm.run().unwrap();
    let marker: u32 = vm
        .guest_mem()
        .memory()
        .read_obj(GuestAddress(0x210004))
        .unwrap();
    assert_eq!(marker, 0x600d600d, "native startup/two-IPI control");
    for id in 0..count {
        let rows: Vec<_> = QUERIES
            .iter()
            .map(|&(leaf, index)| profile_cpuid(&vm, id, leaf, index))
            .collect();
        println!("native_profile_cpus={count} cpu={id} records={rows:x?}");
    }
    use rax::backend::Backend;
    let backend = rax::backend::kvm::KvmBackend::new().unwrap();
    let raw_vm = backend.create_vm().unwrap();
    let raw_vm = raw_vm
        .as_any()
        .downcast_ref::<rax::backend::kvm::KvmVm>()
        .unwrap();
    let native_khz = raw_vm.create_vcpu_fd(0).unwrap().get_tsc_khz().unwrap();
    let shift = u8::BITS - (count - 1).leading_zeros();
    for id in 0..count {
        let basic = profile_cpuid(&vm, id, 0, 0);
        if !clock_only {
            let version = profile_cpuid(&vm, id, 1, 0);
            assert_eq!(version[1] >> 24, u32::from(id), "initial APIC identity");
            assert_eq!(
                (version[1] >> 16) & 255,
                u32::from(count),
                "logical package capacity"
            );
            assert_eq!(
                (version[3] >> 28) & 1,
                u32::from(count > 1),
                "HTT topology flag"
            );
            assert!(basic[0] >= 0xb, "native topology enumeration is missing");
            for leaf in [0xb, 0x1f].into_iter().filter(|leaf| *leaf <= basic[0]) {
                assert_eq!(
                    profile_cpuid(&vm, id, leaf, 0),
                    [0, 1, 0x100, u32::from(id)],
                    "single thread per core"
                );
                assert_eq!(
                    profile_cpuid(&vm, id, leaf, 1),
                    [shift, u32::from(count), 0x201, u32::from(id)],
                    "configured cores per package"
                );
                assert_eq!(
                    profile_cpuid(&vm, id, leaf, 2),
                    [0, 0, 2, u32::from(id)],
                    "topology terminator"
                );
            }
            for index in 0..8 {
                let cache = profile_cpuid(&vm, id, 4, index);
                if cache[0] & 31 == 0 {
                    break;
                }
                assert_eq!(
                    (cache[0] >> 26) + 1,
                    u32::from(count),
                    "cache package capacity"
                );
                let level = (cache[0] >> 5) & 7;
                let expected_sharing = if level <= 2 { 1 } else { u32::from(count) };
                assert_eq!(
                    ((cache[0] >> 14) & 4095) + 1,
                    expected_sharing,
                    "virtual cache sharing"
                );
            }
        }
        assert_ne!(
            profile_cpuid(&vm, id, 1, 0)[2] & (1 << 31),
            0,
            "native KVM signature/features are hidden by the absent hypervisor bit"
        );
        let signature = profile_cpuid(&vm, id, 0x40000000, 0);
        assert!(signature[0] == 0 || signature[0] >= 0x40000001);
        assert_eq!(&signature[1..], &[0x4b4d564b, 0x564b4d56, 0x4d]);
        assert_ne!(
            profile_cpuid(&vm, id, 0x40000001, 0)[0] & 8,
            0,
            "native clocksource2 profile"
        );
        let mut clock = [0u8; 32];
        vm.guest_mem()
            .memory()
            .read_slice(&mut clock, GuestAddress(0x260000 + u64::from(id) * 4096))
            .unwrap();
        let version = u32::from_le_bytes(clock[..4].try_into().unwrap());
        assert_ne!(version, 0, "native kernel did not publish a clock page");
        assert_eq!(
            version & 1,
            0,
            "native clock page publication is incomplete"
        );
        let timestamp = u64::from_le_bytes(clock[8..16].try_into().unwrap());
        let system_time = u64::from_le_bytes(clock[16..24].try_into().unwrap());
        let multiplier = u32::from_le_bytes(clock[24..28].try_into().unwrap());
        assert!(timestamp > 0 && system_time > 0 && multiplier > 0);
        let shift = clock[28] as i8;
        let mut khz = (1_000_000u64 << 32) / u64::from(multiplier);
        khz = if shift < 0 {
            khz.checked_shl((-i16::from(shift)) as u32).unwrap()
        } else {
            khz.checked_shr(shift as u32).unwrap()
        };
        assert!(
            khz.abs_diff(u64::from(native_khz)) <= 1,
            "PV clock rate{khz}kHz disagrees with native SDK rate{native_khz}kHz"
        );
        println!(
            "native_clock_cpu={id} version={version} system_time_ns={system_time} tsc_khz={khz}"
        );
    }
}

