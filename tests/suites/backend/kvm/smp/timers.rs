use rax::config::{ArchKind, BackendKind, CliConfig, MemorySize, VmConfig};
use rax::vm::Vmm;
use rax::vm::memory::vm::{Bytes, GuestAddress};
use std::io::Write;
use std::path::PathBuf;
use std::process::{Command, Stdio};
use std::time::{Duration, Instant};

struct Kernel(PathBuf);
impl Drop for Kernel {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
    }
}

fn run(count: u8, deadline: bool, name: &str) {
    const CHILD: &str = "RAX_KVM_NATIVE_TIMER_TEST_CHILD";
    if std::env::var(CHILD).as_deref() != Ok(name) {
        let mut child = Command::new(std::env::current_exe().unwrap())
            .args([
                "--include-ignored",
                "--exact",
                name,
                "--nocapture",
                "--test-threads=1",
            ])
            .env(CHILD, name)
            .stdout(Stdio::piped())
            .stderr(Stdio::piped())
            .spawn()
            .unwrap();
        let started = Instant::now();
        loop {
            if child.try_wait().unwrap().is_some() {
                break;
            }
            if started.elapsed() >= Duration::from_secs(40) {
                child.kill().unwrap();
                let output = child.wait_with_output().unwrap();
                panic!(
                    "owned timer guest exceeded40s: {}\n{}",
                    String::from_utf8_lossy(&output.stdout),
                    String::from_utf8_lossy(&output.stderr)
                );
            }
            std::thread::sleep(Duration::from_millis(10));
        }
        let output = child.wait_with_output().unwrap();
        assert!(
            output.status.success(),
            "{}\n{}\n{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        print!("{}", String::from_utf8_lossy(&output.stdout));
        return;
    }
    let path = std::env::temp_dir().join(format!(
        "rax-kvm-timer-{}-{count}-{deadline}",
        std::process::id()
    ));
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .unwrap();
    let kernel = Kernel(path);
    let mut image = vec![0; 0x200];
    image.extend_from_slice(TIMER_BSP);
    assert!(image.len() <= 0x1200);
    image.resize(0x1200, 0);
    image.extend_from_slice(TIMER_AP);
    image.resize(0x2200, 0);
    file.write_all(&image).unwrap();
    drop(file);
    let mut config = VmConfig::from_sources(
        CliConfig {
            arch: Some(ArchKind::X86_64),
            backend: Some(BackendKind::Kvm),
            vcpus: Some(count),
            kernel: Some(kernel.0.clone()),
            ..Default::default()
        },
        None,
    )
    .unwrap();
    config.memory = MemorySize(64 * 1024 * 1024);
    let mut vm = Vmm::new(config).unwrap();
    vm.guest_mem()
        .memory()
        .write_obj(u32::from(count), GuestAddress(0x210000))
        .unwrap();
    vm.guest_mem()
        .memory()
        .write_obj(u32::from(deadline), GuestAddress(0x210008))
        .unwrap();
    vm.run().unwrap();
    let marker: u32 = vm
        .guest_mem()
        .memory()
        .read_obj(GuestAddress(0x210004))
        .unwrap();
    let counts: Vec<u32> = (0..count)
        .map(|id| {
            vm.guest_mem()
                .memory()
                .read_obj(GuestAddress(0x200004 + u64::from(id) * 8))
                .unwrap()
        })
        .collect();
    let ready: Vec<u32> = (0..count)
        .map(|id| {
            vm.guest_mem()
                .memory()
                .read_obj(GuestAddress(0x200000 + u64::from(id) * 8))
                .unwrap()
        })
        .collect();
    let missing: Vec<u32> = (0..count)
        .map(|id| {
            vm.guest_mem()
                .memory()
                .read_obj(GuestAddress(0x220000 + u64::from(id) * 4))
                .unwrap()
        })
        .collect();
    println!(
        "native_timer_cpus={count} deadline={deadline} marker={marker:#x} ready={ready:x?} irq_counts={counts:?} missing={missing:?}"
    );
    assert_eq!(
        marker, 0x600d0042,
        "every CPU must receive both native timer IRQs"
    );
    assert!(ready.iter().all(|value| *value == 0xa5a55a5a));
    assert!(counts.iter().all(|value| *value == 2));
    assert!(missing.iter().all(|value| *value == 0));
}

