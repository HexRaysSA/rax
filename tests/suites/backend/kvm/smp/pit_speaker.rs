fn run_speaker(code: &[u8], width: u8, name: &str) {
    if std::env::var(CHILD).as_deref() != Ok(name) {
        let output = Command::new(std::env::current_exe().unwrap())
            .args([
                "--ignored",
                "--exact",
                name,
                "--nocapture",
                "--test-threads=1",
            ])
            .env(CHILD, name)
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}\n{}\n{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        print!("{}", String::from_utf8_lossy(&output.stdout));
        return;
    }
    let path = std::env::temp_dir().join(format!("rax-native-pit-{}-{width}", std::process::id()));
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .unwrap();
    let kernel = Kernel(path);
    let mut image = vec![0; 0x200];
    image.extend_from_slice(code);
    file.write_all(&image).unwrap();
    drop(file);
    let mut config = VmConfig::from_sources(
        CliConfig {
            arch: Some(ArchKind::X86_64),
            backend: Some(BackendKind::Kvm),
            vcpus: Some(1),
            kernel: Some(kernel.0.clone()),
            ..Default::default()
        },
        None,
    )
    .unwrap();
    config.memory = MemorySize(64 * 1024 * 1024);
    let mut vm = Vmm::new(config).unwrap();
    vm.run().unwrap();
    let marker: u32 = vm
        .guest_mem()
        .memory()
        .read_obj(GuestAddress(0x211000))
        .unwrap();
    println!("native_pit_port61_width={width} marker={marker:#x}");
    assert_eq!(
        marker, 0x600d0061,
        "native channel2 completion did not reach port61 OUT/readback"
    );
}

