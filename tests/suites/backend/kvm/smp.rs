struct Kernel(PathBuf);
impl Drop for Kernel {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
    }
}

fn run(count: u8, name: &str) {
    if std::env::var(CHILD).as_deref() != Ok(name) {
        let output = Command::new(std::env::current_exe().unwrap())
            .args([
                "--ignored",
                "--exact",
                name,
                "--nocapture",
                "--test-threads=1",
            ])
            .env(CHILD, name)
            .output()
            .unwrap();
        assert!(
            output.status.success(),
            "{}\n{}\n{}",
            output.status,
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        print!("{}", String::from_utf8_lossy(&output.stdout));
        return;
    }
    let path = std::env::temp_dir().join(format!("rax-kvm-smp-{}-{count}", std::process::id()));
    let mut file = std::fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&path)
        .unwrap();
    let kernel = Kernel(path);
    let mut image = vec![0; 0x200];
    image.extend_from_slice(BSP);
    image.resize(0x1200, 0);
    image.extend_from_slice(AP);
    image.resize(0x1300, 0);
    file.write_all(&image).unwrap();
    drop(file);
    let mut config = VmConfig::from_sources(
        CliConfig {
            arch: Some(ArchKind::X86_64),
            backend: Some(BackendKind::Kvm),
            vcpus: Some(count),
            kernel: Some(kernel.0.clone()),
            ..Default::default()
        },
        None,
    )
    .unwrap();
    config.memory = MemorySize(64 * 1024 * 1024);
    let mut vm = Vmm::new(config).unwrap();
    vm.guest_mem()
        .memory()
        .write_obj(u32::from(count), GuestAddress(0x210000))
        .unwrap();
    vm.run().unwrap();
    let marker: u32 = vm
        .guest_mem()
        .memory()
        .read_obj(GuestAddress(0x210004))
        .unwrap();
    let flags: Vec<u32> = (0..count)
        .map(|id| {
            vm.guest_mem()
                .memory()
                .read_obj(GuestAddress(0x200000 + u64::from(id) * 8))
                .unwrap()
        })
        .collect();
    let ipi_counts: Vec<u32> = (0..count)
        .map(|id| {
            vm.guest_mem()
                .memory()
                .read_obj(GuestAddress(0x200004 + u64::from(id) * 8))
                .unwrap()
        })
        .collect();
    let cpuid_ids: Vec<u32> = (0..count)
        .map(|id| {
            vm.guest_mem()
                .memory()
                .read_obj(GuestAddress(0x220000 + u64::from(id) * 4))
                .unwrap()
        })
        .collect();
    println!(
        "native_vmm_cpus={count} marker={marker:#x} flags={flags:x?} ipi_counts={ipi_counts:?} cpuid_ids={cpuid_ids:?}"
    );
    assert_eq!(
        marker, 0x600d600d,
        "BSP exhausted its bounded wait for secondary CPU work"
    );
    assert!(flags.iter().all(|flag| *flag == 0xa5a55a5a));
    assert!(
        ipi_counts.iter().skip(1).all(|count| *count == 2),
        "each AP must wake for both fixed IPIs and acknowledge with EOI"
    );
    for id in 0..count {
        let words: [u32; 5] = std::array::from_fn(|word| {
            vm.guest_mem()
                .memory()
                .read_obj(GuestAddress(
                    0x230000 + u64::from(id) * 32 + word as u64 * 4,
                ))
                .unwrap()
        });
        println!("native_cpu={id} topology_words={words:x?}");
        for (leaf, initial_id, logical_count) in
            [(0xb, words[1], words[3]), (0x1f, words[2], words[4])]
        {
            if words[0] >= leaf && logical_count & 0xffff != 0 {
                assert_eq!(
                    initial_id,
                    u32::from(id),
                    "topology leaf {leaf:#x} reports a foreign APIC identity"
                );
            }
        }
    }
    assert_eq!(
        cpuid_ids,
        (0..u32::from(count)).collect::<Vec<_>>(),
        "CPUID initial APIC identities differ from the executing native CPUs"
    );
}

