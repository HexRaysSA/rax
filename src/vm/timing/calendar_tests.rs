#[test]
fn selected_calendar_retains_owner_and_ignores_foreign_time_and_host_delay() {
    let vm = Arc::new(TimingContext::with_mode(ClockMode::Retired));
    let _scope = vm.enter();
    let clock = CalendarClock::selected();
    let origin = Duration::from_secs(RETIRED_CALENDAR_ORIGIN);
    assert_eq!(clock.timestamp(), origin);
    std::thread::sleep(Duration::from_millis(2));
    assert_eq!(clock.timestamp(), origin);
    let other = Arc::new(TimingContext::with_mode(ClockMode::Retired));
    other.advance_retired(3_000_000_000).unwrap();
    let _foreign = other.enter();
    assert_eq!(clock.timestamp(), origin);
    vm.advance_retired(2).unwrap();
    assert_eq!(clock.timestamp(), origin);
    vm.advance_retired(1).unwrap();
    assert_eq!(clock.timestamp(), origin + Duration::from_nanos(1));
    let mut incoming = vm.checkpoint_state();
    incoming.elapsed_nanos = 60_000_000_000;
    incoming.retired_units = 180_000_000_002;
    incoming.subnanosecond_quanta = 2;
    vm.restore_checkpoint_state(&incoming).unwrap();
    assert_eq!(clock.timestamp(), origin + Duration::from_secs(60));
    vm.advance_retired(1).unwrap();
    assert_eq!(clock.timestamp(), origin + Duration::new(60, 1));
}
#[test]
fn selected_calendar_uses_the_defined_wrapping_nanosecond_epoch() {
    let vm = Arc::new(TimingContext::with_mode(ClockMode::Retired));
    let _scope = vm.enter();
    let clock = CalendarClock::selected();
    let mut state = vm.checkpoint_state();
    state.elapsed_nanos = u64::MAX;
    vm.restore_checkpoint_state(&state).unwrap();
    assert_eq!(
        clock.timestamp(),
        Duration::from_secs(RETIRED_CALENDAR_ORIGIN) + Duration::from_nanos(u64::MAX)
    );
    vm.advance_retired(3).unwrap();
    assert_eq!(
        clock.timestamp(),
        Duration::from_secs(RETIRED_CALENDAR_ORIGIN)
    );
}
#[test]
fn wall_calendar_does_not_rebind_under_a_retired_ambient_scope() {
    let wall = CalendarClock::selected();
    assert!(!wall.is_retired());
    let vm = Arc::new(TimingContext::with_mode(ClockMode::Retired));
    let _scope = vm.enter();
    assert!(!wall.is_retired());
    assert!(CalendarClock::selected().is_retired());
}
