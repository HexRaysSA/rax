/// Reason for execution exit
#[derive(Clone, Debug)]
pub enum ExitReason {
    /// Exact AArch64 CPU fault before retirement; no inferred generic syndrome.
    Aarch64Fault {
        pc: GuestAddr,
        error: crate::isa::arm::common::cpu::ArmError,
    },
    /// Precise AArch64 synchronous exception, before architectural entry.
    Aarch64Exception {
        pc: GuestAddr,
        ec: u8,
        iss: u32,
        target_el: u8,
    },
    /// A precise eBPF / SBPF execution trap.
    EbpfTrap(crate::isa::ebpf::EbpfTrap),
    /// Reached instruction limit
    InsnLimit,
    /// Halt instruction
    Halt,
    /// System call
    Syscall { num: u64, args: Vec<u64> },
    /// Breakpoint hit
    Breakpoint { addr: GuestAddr },
    /// Memory fault
    MemoryFault { addr: GuestAddr, write: bool },
    /// Data alignment failed before any memory access or destination update.
    AlignmentFault {
        pc: GuestAddr,
        address: GuestAddr,
        alignment: u32,
        access: crate::error::MemoryAccessKind,
    },
    /// The selected execution backend cannot represent this operation.
    Unsupported {
        addr: GuestAddr,
        operation: &'static str,
    },
    /// Undefined instruction
    Undefined { addr: GuestAddr, opcode: u32 },
    /// x86 general-protection exception with its architectural error code.
    GeneralProtection { addr: GuestAddr, error_code: u32 },
    /// x86 alignment-check exception. Architecturally #AC pushes error code
    /// zero; the address identifies the faulting guest instruction.
    AlignmentCheck { addr: GuestAddr },
    /// x86 segment-not-present exception with its selector-derived error code.
    SegmentNotPresent { addr: GuestAddr, error_code: u32 },
    /// Fault-class x86 debug exception, including DR7.GD general detect.
    Debug { addr: GuestAddr },
    /// Pending x86 breakpoint exception generated by `INT3` (`CC`).
    ///
    /// This is distinct from both an emulator/debugger breakpoint and
    /// `INT imm8` with vector 3: architecture integration must preserve the
    /// dedicated INT3 delivery rules. `return_pc` is the post-instruction RIP
    /// to save if delivery succeeds; delivery faults are attributed to
    /// `fault_pc`.
    X86Breakpoint {
        fault_pc: GuestAddr,
        return_pc: GuestAddr,
    },
    /// Pending x86 software interrupt generated by `INT imm8`.
    ///
    /// The architecture integration must perform IDT/IVT lookup, software-gate
    /// privilege checks, and fault-precise frame construction. `return_pc` is
    /// the post-instruction RIP to save if delivery succeeds; delivery faults
    /// are attributed to `fault_pc`.
    X86SoftwareInterrupt {
        vector: u8,
        fault_pc: GuestAddr,
        return_pc: GuestAddr,
    },
    /// Pending x86 interrupt return generated by `IRET`/`IRETD`/`IRETQ`.
    ///
    /// The architecture integration must execute the complete fault-precise
    /// return sequence, beginning at `fault_pc`, using the encoded operand
    /// width. No stack, descriptor, flag, or control-flow state has been
    /// committed by SMIR when this exit is reported.
    X86InterruptReturn { width: OpWidth, fault_pc: GuestAddr },
    /// Pending x86 `INS*`/`OUTS*` string port-I/O operation.
    ///
    /// The architecture integration must re-execute the operation beginning at
    /// `fault_pc`; SMIR has not performed the port access, memory access, or any
    /// REP/index/count update. `return_pc` is the eventual successful
    /// fallthrough after the last requested element.
    X86StringIo {
        kind: X86StringIoKind,
        width: MemWidth,
        address_width: OpWidth,
        repeated: bool,
        memory_segment: X86Segment,
        fault_pc: GuestAddr,
        return_pc: GuestAddr,
    },
    /// x86 stack-segment exception with its architectural error code.
    StackSegment { addr: GuestAddr, error_code: u32 },
    /// x86 invalid-TSS exception with its selector-derived error code.
    InvalidTss { addr: GuestAddr, error_code: u32 },
    /// x86 unmasked SIMD floating-point exception (#XM).
    SimdFloatingPoint { addr: GuestAddr },
    /// External interrupt
    Interrupt { vector: u8 },
    /// Self-modifying code detected
    SmcDetected { addr: GuestAddr },
    /// Single step complete
    SingleStep,
    /// Function return
    Return { to: GuestAddr },
    /// Block not found (needs lifting)
    BlockNotFound { addr: GuestAddr },
}

