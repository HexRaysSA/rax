/// Bridges the RISC-V `Memory` trait to the SMIR memory for the lifetime of one
/// transient-CPU vector instruction. A raw pointer is used because riscv
/// `Memory::read` is `&self` whereas `SmirMemory::read` is `&mut self`, and the
/// SMIR memory is exclusively borrowed by the interp for the whole RvVector
/// handler — so the aliasing is sound and single-threaded.
struct RvVecMemBridge {
    mem: *mut dyn SmirMemory,
}
impl std::fmt::Debug for RvVecMemBridge {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("RvVecMemBridge")
    }
}
// SAFETY: only dereferenced single-threaded within one `exec_rv_vector` call,
// where the underlying `&mut dyn SmirMemory` is alive and exclusively held.
unsafe impl Send for RvVecMemBridge {}
impl crate::isa::riscv::Memory for RvVecMemBridge {
    fn read(&self, addr: u64, buf: &mut [u8]) -> crate::isa::riscv::MemResult<()> {
        unsafe {
            (*self.mem)
                .read(addr, buf)
                .map_err(|_| crate::isa::riscv::MemError::OutOfBounds {
                    addr,
                    size: buf.len(),
                })
        }
    }
    fn write(&mut self, addr: u64, data: &[u8]) -> crate::isa::riscv::MemResult<()> {
        unsafe {
            (*self.mem)
                .write(addr, data)
                .map_err(|_| crate::isa::riscv::MemError::OutOfBounds {
                    addr,
                    size: data.len(),
                })
        }
    }
}

fn forward_rv_vector_scalar_state(ctx: &mut SmirContext, state: &RvVectorState) {
    let x: [u64; 32] = std::array::from_fn(|i| ctx.read_vreg(state.x_srcs[i]));
    let f: [u64; 32] = std::array::from_fn(|i| ctx.read_vreg(state.f_srcs[i]));
    let fcsr = ctx.read_vreg(state.fcsr_src);
    let vl = ctx.read_vreg(state.vl_src);
    let vtype = ctx.read_vreg(state.vtype_src);
    let vstart = ctx.read_vreg(state.vstart_src);
    let vcsr = ctx.read_vreg(state.vcsr_src);

    for i in 1..32usize {
        ctx.write_vreg(state.x_dsts[i], x[i]);
    }
    for i in 0..32usize {
        ctx.write_vreg(state.f_dsts[i], f[i]);
    }
    ctx.write_vreg(state.fcsr_dst, fcsr);
    ctx.write_vreg(state.vl_dst, vl);
    ctx.write_vreg(state.vtype_dst, vtype);
    ctx.write_vreg(state.vstart_dst, vstart);
    ctx.write_vreg(state.vcsr_dst, vcsr);
}

/// Execute one RVV instruction bit-exactly by loading the SMIR machine state
/// into a transient `RiscVCpu` (over a bridge to the SMIR memory), running the
/// qemu-verified vector engine, and reading the full result state back. RVV
/// element width/count are runtime `vtype`/`vl` state, so this opaque delegation
/// is the only faithful lift. The interpreter exits at the instruction PC on a
/// trap. Precise vector-memory traps publish the faulting element in `vstart`
/// and retain completed load elements; illegal encodings remain fully
/// transactional.
fn exec_rv_vector(
    ctx: &mut SmirContext,
    memory: &mut dyn SmirMemory,
    insn: u32,
    xlen: u8,
    guest_pc: u64,
    state: &RvVectorState,
) {
    let pc = guest_pc;
    let v = match &ctx.arch_regs {
        ArchRegState::RiscV(rv) => rv.v,
        _ => return,
    };

    // Lifetime-erase the SMIR memory pointer into the 'static bridge; the bridge
    // (and the CPU owning it) is dropped before this function returns, so it
    // never outlives the borrow.
    let memptr: *mut dyn SmirMemory =
        unsafe { std::mem::transmute::<*mut dyn SmirMemory, *mut dyn SmirMemory>(memory) };
    let bridge = RvVecMemBridge { mem: memptr };
    let (config, decode_xlen) = match xlen {
        32 => (
            crate::isa::riscv::RiscVConfig::rv32(crate::isa::riscv::Isa::rv64gc()),
            crate::isa::riscv::Xlen::Rv32,
        ),
        64 => (
            crate::isa::riscv::RiscVConfig::rv64gc(),
            crate::isa::riscv::Xlen::Rv64,
        ),
        _ => {
            forward_rv_vector_scalar_state(ctx, state);
            ctx.request_exit(ExitReason::Undefined {
                addr: guest_pc,
                opcode: insn,
            });
            return;
        }
    };
    let mut cpu = crate::isa::riscv::RiscVCpu::new(config, Box::new(bridge));
    // RvVectorState does not carry privilege or mstatus; the owning RISC-V
    // execution path gates FP before lifting, so the transient bridge enables
    // the already-admitted vector FP operation here.
    cpu.csr_write(0x300, 0b01 << 13)
        .expect("transient vector hart must expose mstatus");
    for i in 1..32u8 {
        cpu.set_x(i, ctx.read_vreg(state.x_srcs[i as usize]));
    }
    for i in 0..32u8 {
        cpu.set_f(i, ctx.read_vreg(state.f_srcs[i as usize]));
    }
    cpu.set_fcsr(ctx.read_vreg(state.fcsr_src) as u32);
    for i in 0..32u8 {
        cpu.set_vreg(i, &v[i as usize]);
    }
    cpu.set_vl_vtype(ctx.read_vreg(state.vl_src), ctx.read_vreg(state.vtype_src));
    cpu.set_vstart(ctx.read_vreg(state.vstart_src));
    cpu.set_vcsr(ctx.read_vreg(state.vcsr_src));

    let isa = crate::isa::riscv::Isa::rv64gc();
    let d = crate::isa::riscv::decode(insn, decode_xlen, &isa);
    if d.is_illegal() {
        forward_rv_vector_scalar_state(ctx, state);
        ctx.request_exit(ExitReason::Undefined {
            addr: guest_pc,
            opcode: insn,
        });
        return;
    }

    let execution = cpu.execute_insn(&d, pc);
    if !matches!(execution, Ok(crate::isa::riscv::RiscVExit::Continue)) {
        forward_rv_vector_scalar_state(ctx, state);

        if let Err(trap) = execution
            && matches!(
                trap.cause,
                crate::isa::riscv::cpu::cause::LOAD_MISALIGNED
                    | crate::isa::riscv::cpu::cause::LOAD_ACCESS_FAULT
                    | crate::isa::riscv::cpu::cause::STORE_MISALIGNED
                    | crate::isa::riscv::cpu::cause::STORE_ACCESS_FAULT
            )
        {
            let vstart_out = cpu.vstart();
            ctx.write_vreg(state.vstart_dst, vstart_out);
            if let ArchRegState::RiscV(rv) = &mut ctx.arch_regs {
                for register in 0..32u8 {
                    rv.v[register as usize] = cpu.vreg(register);
                }
                rv.vstart = vstart_out;
            }
        }

        ctx.request_exit(ExitReason::Undefined {
            addr: guest_pc,
            opcode: insn,
        });
        return;
    }

    let mut x_out = [0u64; 32];
    let mut f_out = [0u64; 32];
    let mut v_out = [[0u8; 16]; 32];
    for i in 1..32u8 {
        x_out[i as usize] = cpu.x(i);
    }
    for i in 0..32u8 {
        f_out[i as usize] = cpu.f(i);
        v_out[i as usize] = cpu.vreg(i);
    }
    let fcsr_out = cpu.fcsr();
    let vl_out = cpu.vl();
    let vtype_out = cpu.vtype();
    let vstart_out = cpu.vstart();
    let vcsr_out = cpu.vcsr();

    for i in 1..32usize {
        ctx.write_vreg(state.x_dsts[i], x_out[i]);
    }
    for i in 0..32usize {
        ctx.write_vreg(state.f_dsts[i], f_out[i]);
    }
    ctx.write_vreg(state.fcsr_dst, fcsr_out as u64);
    ctx.write_vreg(state.vl_dst, vl_out);
    ctx.write_vreg(state.vtype_dst, vtype_out);
    ctx.write_vreg(state.vstart_dst, vstart_out);
    ctx.write_vreg(state.vcsr_dst, vcsr_out);

    if let ArchRegState::RiscV(rv) = &mut ctx.arch_regs {
        for i in 1..32u8 {
            rv.x[i as usize] = x_out[i as usize];
        }
        for i in 0..32u8 {
            rv.f[i as usize] = f_out[i as usize];
        }
        rv.fcsr = fcsr_out;
        for i in 0..32u8 {
            rv.v[i as usize] = v_out[i as usize];
        }
        rv.vl = vl_out;
        rv.vtype = vtype_out;
        rv.vstart = vstart_out;
        rv.vcsr = vcsr_out;
    }
}
